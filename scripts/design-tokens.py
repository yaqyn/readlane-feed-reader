#!/usr/bin/env python3
"""Generate Readlane's runtime palette and canonical documentation icons."""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parents[1]
front = json.loads((root / 'DESIGN.md').read_text().split('---', 2)[1])
colors = front['colors']
css = '/* Generated from DESIGN.md by scripts/design-tokens.py. */\n:root {\n'
for key, value in colors.items():
    css += f'  --color-{key}: {value};\n'
for key, value in front['rounded'].items():
    css += f'  --radius-{key.lower()}: {value};\n'
for key, value in front['spacing'].items():
    css += f'  --{key}: {value};\n'
css += '}\n'
palette = '// Code generated by scripts/design-tokens.py from DESIGN.md. DO NOT EDIT.\npackage app\n\nconst (\n'
for key, value in colors.items():
    name = 'brand' + ''.join(part.title() for part in key.split('-'))
    palette += f'\t{name} = "{value}"\n'
palette += ')\n'
outputs = {root / 'internal/web/assets/tokens.css': css, root / 'internal/app/palette_generated.go': palette}
for path in (root / 'readme-assets/icons').glob('*.svg'):
    import re
    old = path.read_text()
    recolored = re.sub(r'fill="#[0-9a-fA-F]{6}"', 'fill="' + colors['tint'] + '"', old)
    recolored = re.sub(r'stroke="#[0-9a-fA-F]{6}"', 'stroke="' + colors['primary'] + '"', recolored)
    outputs[path] = recolored
for path, text in outputs.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != text:
            raise SystemExit('Design token drift: ' + str(path.relative_to(root)))
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
print('Design tokens and canonical icon palette checked' if '--check' in sys.argv else 'Design tokens and canonical icon palette generated')
